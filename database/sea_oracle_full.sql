-- 4. PARTIDAS PRESUPUESTARIAS
CREATE TABLE PARTIDAS_PRESUPUESTARIAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_PARTIDA VARCHAR2(50) NOT NULL UNIQUE,
