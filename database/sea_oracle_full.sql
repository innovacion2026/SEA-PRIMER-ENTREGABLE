-- BORRADO PREVIO DE TABLAS (SI EXISTEN)
BEGIN
   FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
       'RENDICION_GASTOS','VIATICOS_SOPORTES','VIATICOS_MOVIMIENTOS','VIATICOS_PARAMETROS','VIATICOS',
       'CAJA_CHICA_SOPORTES','CAJA_CHICA_PARAMETROS','CAJA_CHICA','PAGOS','RETENCIONES','CXP',
       'RECEPCIONES_ALMACEN','ORDENES_COMPRA_ITEMS','ORDENES_COMPRA','LICITACION_OFERTAS',
       'LICITACIONES_SELECCION','SOLICITUDES_COMPRA','PRESUPUESTO_MODIFICACIONES',
       'PRESUPUESTO_TRAZABILIDAD','PARTIDAS_PRESUPUESTARIAS','DOCUMENTOS_PROVEEDOR',
       'SOLICITUDES_INGRESO_PROVEEDOR','PROVEEDORES','ROLES','USUARIOS','COMPANIA',
       'PARAMETROS_BASE','LISTA_VALORES','AUDITORIA','PAGOS_LIQUIDADOS','FACTURAS_CXP'
   )) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE "' || t.table_name || '" CASCADE CONSTRAINTS';
   END LOOP;
EXCEPTION
   WHEN OTHERS THEN NULL;
END;
