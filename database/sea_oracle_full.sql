-- 1. PROVEEDORES
CREATE TABLE PROVEEDORES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RIF VARCHAR2(20) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(150) NOT NULL,
    CATEGORIA VARCHAR2(100),
    ESTATUS VARCHAR2(30) DEFAULT 'Activo',
    BANCO VARCHAR2(100),
    CUENTA_BANCARIA VARCHAR2(30),
    EMAIL VARCHAR2(100),
    TELEFONO VARCHAR2(30),
    FECHA_REGISTRO DATE DEFAULT SYSDATE
);

-- 2. SOLICITUDES INGRESO PROVEEDOR
CREATE TABLE SOLICITUDES_INGRESO_PROVEEDOR (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RIF VARCHAR2(20) NOT NULL,
    PROVEEDOR VARCHAR2(150) NOT NULL,
    CATEGORIA VARCHAR2(100),
    EMAIL VARCHAR2(100) NOT NULL,
    TELEFONO VARCHAR2(30),
    ESTATUS VARCHAR2(30) DEFAULT 'Invitado',
    TOKEN_INVITACION VARCHAR2(100),
    BANCO_NOMBRE VARCHAR2(100),
    CUENTA_20_DIGITOS VARCHAR2(30),
    TITULAR_CUENTA VARCHAR2(150),
    EXPEDIENTE_APROBADO NUMBER(1) DEFAULT 0,
    FECHA_INVITACION DATE DEFAULT SYSDATE,
    FECHA_REGISTRO DATE
);

-- 3. DOCUMENTOS PROVEEDOR
CREATE TABLE DOCUMENTOS_PROVEEDOR (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROVEEDOR_ID NUMBER REFERENCES PROVEEDORES(ID),
    NOMBRE_DOCUMENTO VARCHAR2(150) NOT NULL,
    CATEGORIA VARCHAR2(100),
    NOMBRE_ARCHIVO_PDF VARCHAR2(255) NOT NULL,
    PESO_ARCHIVO VARCHAR2(30),
    FECHA_CARGA DATE DEFAULT SYSDATE,
    FECHA_VENCIMIENTO DATE,
    ESTATUS_VALIDACION VARCHAR2(30) DEFAULT 'PENDIENTE',
    ORIGEN_CARGA VARCHAR2(50) DEFAULT 'Portal Proveedores'
