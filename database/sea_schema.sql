-- 1. TABLA MAESTRA DE PROVEEDORES
CREATE TABLE PROVEEDORES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RIF VARCHAR2(20) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(150) NOT NULL,
    CATEGORIA VARCHAR2(100),
    ESTATUS VARCHAR2(30) DEFAULT 'Activo',
    BANCO VARCHAR2(100),
    CUENTA_BANCARIA VARCHAR2(30),
    EMAIL VARCHAR2(100),
    TELEFONO VARCHAR2(30),
    FECHA_REGISTRO DATE DEFAULT SYSDATE
);

-- 2. TABLA DE SOLICITUDES DE INGRESO Y ONBOARDING DE PROVEEDORES
CREATE TABLE SOLICITUDES_INGRESO_PROVEEDOR (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RIF VARCHAR2(20) NOT NULL,
    PROVEEDOR VARCHAR2(150) NOT NULL,
    CATEGORIA VARCHAR2(100),
    EMAIL VARCHAR2(100) NOT NULL,
    TELEFONO VARCHAR2(30),
    ESTATUS VARCHAR2(30) DEFAULT 'Invitado',
    TOKEN_INVITACION VARCHAR2(100),
    BANCO_NOMBRE VARCHAR2(100),
    CUENTA_20_DIGITOS VARCHAR2(30),
    TITULAR_CUENTA VARCHAR2(150),
    EXPEDIENTE_APROBADO NUMBER(1) DEFAULT 0,
    FECHA_INVITACION DATE DEFAULT SYSDATE,
    FECHA_REGISTRO DATE
);

-- 3. BÓVEDA DE DOCUMENTOS Y RECAUDOS DE PROVEEDORES
CREATE TABLE DOCUMENTOS_PROVEEDOR (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROVEEDOR_ID NUMBER REFERENCES PROVEEDORES(ID),
    NOMBRE_DOCUMENTO VARCHAR2(150) NOT NULL,
    CATEGORIA VARCHAR2(100),
    NOMBRE_ARCHIVO_PDF VARCHAR2(255) NOT NULL,
    PESO_ARCHIVO VARCHAR2(30),
    FECHA_CARGA DATE DEFAULT SYSDATE,
    FECHA_VENCIMIENTO DATE,
    ESTATUS_VALIDACION VARCHAR2(30) DEFAULT 'PENDIENTE',
    ORIGEN_CARGA VARCHAR2(50) DEFAULT 'Portal Proveedores'
);

-- 4. MAESTRO DE PARTIDAS PRESUPUESTARIAS
CREATE TABLE PARTIDAS_PRESUPUESTARIAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_PARTIDA VARCHAR2(50) NOT NULL UNIQUE,
    DENOMINACION VARCHAR2(200) NOT NULL,
    CENTRO_COSTO VARCHAR2(100) NOT NULL,
    LIMITE_ANUAL NUMBER(15,2) DEFAULT 0,
    SALDO_DISPONIBLE NUMBER(15,2) DEFAULT 0,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVA'
);

-- 5. TRAZABILIDAD Y RESERVA DE FONDOS (4 MOMENTOS CONTABLES)
CREATE TABLE PRESUPUESTO_TRAZABILIDAD (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARTIDA_CODIGO VARCHAR2(50) REFERENCES PARTIDAS_PRESUPUESTARIAS(CODIGO_PARTIDA),
    PRECOMPROMETIDO NUMBER(15,2) DEFAULT 0,
    COMPROMETIDO NUMBER(15,2) DEFAULT 0,
    CAUSADO NUMBER(15,2) DEFAULT 0,
    PAGADO NUMBER(15,2) DEFAULT 0
);

-- 6. MODIFICACIONES PRESUPUESTARIAS (TRASPASOS, CRÉDITOS, REDUCCIONES)
CREATE TABLE PRESUPUESTO_MODIFICACIONES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_MODIFICACION VARCHAR2(50) NOT NULL UNIQUE,
    TIPO_MODIFICACION VARCHAR2(50) NOT NULL,
    PARTIDA_ORIGEN VARCHAR2(100),
    PARTIDA_DESTINO VARCHAR2(100),
    MONTO NUMBER(15,2) NOT NULL,
    ESTATUS_WORKFLOW VARCHAR2(50) DEFAULT 'Pendiente Finanzas',
    FECHA_SOLICITUD DATE DEFAULT SYSDATE
);

-- 7. REQUERIMIENTOS Y SOLICITUDES INTERNAS DE COMPRA
CREATE TABLE SOLICITUDES_COMPRA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_SOLICITUD VARCHAR2(50) NOT NULL UNIQUE,
    PARTIDA_CODIGO VARCHAR2(50) REFERENCES PARTIDAS_PRESUPUESTARIAS(CODIGO_PARTIDA),
    DEPARTAMENTO VARCHAR2(100) NOT NULL,
    SOLICITANTE VARCHAR2(100) NOT NULL,
    CONCEPTO VARCHAR2(255) NOT NULL,
    MONTO NUMBER(15,2) NOT NULL,
    ESTATUS VARCHAR2(30) DEFAULT 'Pendiente',
    FECHA_SOLICITUD DATE DEFAULT SYSDATE
);

-- 8. LICITACIÓN / SELECCIÓN DE PROVEEDORES (CUADRO COMPARATIVO 3 OFERTAS)
CREATE TABLE LICITACIONES_SELECCION (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_LICITACION VARCHAR2(50) NOT NULL UNIQUE,
    SOLICITUD_ID NUMBER REFERENCES SOLICITUDES_COMPRA(ID),
    PROVEEDOR_GANADOR_ID NUMBER REFERENCES PROVEEDORES(ID),
    MONTO_ADJUDICADO NUMBER(15,2),
    ESTATUS_CONTRATO VARCHAR2(50) DEFAULT 'Pendiente Firma Proveedor',
    CONTRATO_FIRMADO_PDF VARCHAR2(255),
    FECHA_ADJUDICACION DATE DEFAULT SYSDATE
);

-- 9. OFERTAS COMPARATIVAS DE PROVEEDORES
CREATE TABLE LICITACION_OFERTAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LICITACION_ID NUMBER REFERENCES LICITACIONES_SELECCION(ID),
    PROVEEDOR_ID NUMBER REFERENCES PROVEEDORES(ID),
    PRECIO_OFERTA NUMBER(15,2) NOT NULL,
    DIAS_ENTREGA NUMBER,
    PUNTAJE_CALIDAD NUMBER(5,2),
    GARANTIA VARCHAR2(100),
    ES_GANADOR NUMBER(1) DEFAULT 0
);

-- 10. ÓRDENES DE COMPRA
CREATE TABLE ORDENES_COMPRA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_OC VARCHAR2(50) NOT NULL UNIQUE,
    LICITACION_ID NUMBER REFERENCES LICITACIONES_SELECCION(ID),
    PROVEEDOR_ID NUMBER REFERENCES PROVEEDORES(ID),
    MONTO_TOTAL NUMBER(15,2) NOT NULL,
    ESTATUS_ENTREGA VARCHAR2(50) DEFAULT 'En Proceso Almacén',
    FECHA_EMISION DATE DEFAULT SYSDATE
);

-- 11. CUENTAS POR PAGAR (FACTURAS REGISTRADAS)
CREATE TABLE FACTURAS_CXP (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_FACTURA VARCHAR2(50) NOT NULL UNIQUE,
    ORDEN_COMPRA_ID NUMBER REFERENCES ORDENES_COMPRA(ID),
    PROVEEDOR_ID NUMBER REFERENCES PROVEEDORES(ID),
    MONTO_FACTURA NUMBER(15,2) NOT NULL,
    FECHA_EMISION DATE DEFAULT SYSDATE,
    FECHA_VENCIMIENTO DATE,
    ESTATUS_PAGO VARCHAR2(50) DEFAULT 'Aprobada para Pago'
);

-- 12. RELACIÓN DE PAGOS LIQUIDADOS POR BANCO
CREATE TABLE PAGOS_LIQUIDADOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REFERENCIA_PAGO VARCHAR2(50) NOT NULL UNIQUE,
    FACTURA_ID NUMBER REFERENCES FACTURAS_CXP(ID),
    PROVEEDOR_ID NUMBER REFERENCES PROVEEDORES(ID),
    BANCO_ORIGEN VARCHAR2(100) DEFAULT 'Banco Mercantil',
    CUENTA_DESTINO VARCHAR2(30) NOT NULL,
    MONTO_LIQUIDADO NUMBER(15,2) NOT NULL,
    FECHA_PAGO DATE DEFAULT SYSDATE,
    ESTATUS VARCHAR2(30) DEFAULT 'Procesado'
);

