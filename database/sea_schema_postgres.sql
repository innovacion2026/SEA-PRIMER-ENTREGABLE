-- 5. COMITÉS Y MIEMBROS
CREATE TABLE COMITES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR(50) UNIQUE,
    NOMBRE VARCHAR(150) NOT NULL,
    MONTO_MAX_APROB NUMERIC(15,2),
    FRECUENCIA VARCHAR(50),
    ESTATUS VARCHAR(30) DEFAULT 'Activo',
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE MIEMBROS_COMITE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMITE_ID BIGINT REFERENCES COMITES(ID) ON DELETE CASCADE,
    NOMBRE VARCHAR(150) NOT NULL,
    CARGO VARCHAR(100),
    CEDULA VARCHAR(20),
    EMAIL VARCHAR(100)
);

CREATE TABLE CASOS_COMITE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMITE_ID BIGINT REFERENCES COMITES(ID) ON DELETE CASCADE,
    SOLICITUD_ID BIGINT,
    TITULO VARCHAR(200),
    DESCRIPCION TEXT,
    ESTATUS VARCHAR(50) DEFAULT 'Pendiente',
    DECISION TEXT,
    FECHA_PRESENTACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 6. MAESTRO DE PARTIDAS PRESUPUESTARIAS Y PRESUPUESTOS
CREATE TABLE PARTIDAS_PRESUPUESTARIAS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_PARTIDA VARCHAR(50) NOT NULL UNIQUE,
    DENOMINACION VARCHAR(200) NOT NULL,
    CENTRO_COSTO VARCHAR(100) NOT NULL,
    LIMITE_ANUAL NUMERIC(15,2) DEFAULT 0,
    SALDO_DISPONIBLE NUMERIC(15,2) DEFAULT 0,
    ESTADO VARCHAR(20) DEFAULT 'ACTIVA'
);

CREATE TABLE PRESUPUESTOS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_PARTIDA VARCHAR(50) NOT NULL UNIQUE,
    DENOMINACION VARCHAR(200) NOT NULL,
    CENTRO_COSTO VARCHAR(100) NOT NULL,
    LIMITE_ANUAL NUMERIC(15,2) DEFAULT 0,
    SALDO_DISPONIBLE NUMERIC(15,2) DEFAULT 0,
    ESTADO VARCHAR(20) DEFAULT 'ACTIVA'
);

CREATE TABLE PRESUPUESTO_TRAZABILIDAD (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARTIDA_CODIGO VARCHAR(50) REFERENCES PARTIDAS_PRESUPUESTARIAS(CODIGO_PARTIDA),
    PRECOMPROMETIDO NUMERIC(15,2) DEFAULT 0,
    COMPROMETIDO NUMERIC(15,2) DEFAULT 0,
    CAUSADO NUMERIC(15,2) DEFAULT 0,
    PAGADO NUMERIC(15,2) DEFAULT 0
);

CREATE TABLE PRESUPUESTO_MODIFICACIONES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_MODIFICACION VARCHAR(50) NOT NULL UNIQUE,
    TIPO_MODIFICACION VARCHAR(50) NOT NULL,
    PARTIDA_ORIGEN VARCHAR(100),
    PARTIDA_DESTINO VARCHAR(100),
    MONTO NUMERIC(15,2) NOT NULL,
    ESTATUS_WORKFLOW VARCHAR(50) DEFAULT 'Pendiente Finanzas',
    FECHA_SOLICITUD TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 7. REQUERIMIENTOS Y SOLICITUDES DE COMPRA
CREATE TABLE REQUERIMIENTOS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR(50) UNIQUE,
    TIPO_ORDEN VARCHAR(50),
    SOLICITANTE VARCHAR(100),
    DEPARTAMENTO VARCHAR(100),
    DESCRIPCION TEXT,
    CANTIDAD_UNIDAD VARCHAR(50),
    CENTRO_COSTO VARCHAR(100),
    PRIORIDAD VARCHAR(30),
    ETAPA_NEGOCIO VARCHAR(50) DEFAULT 'Solicitud',
    ESTATUS VARCHAR(30) DEFAULT 'Pendiente',
    MONTO_ESTIMADO NUMERIC(15,2) DEFAULT 0,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE SOLICITUDES_COMPRA (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_SOLICITUD VARCHAR(50) NOT NULL UNIQUE,
    PARTIDA_CODIGO VARCHAR(50) REFERENCES PARTIDAS_PRESUPUESTARIAS(CODIGO_PARTIDA),
    DEPARTAMENTO VARCHAR(100) NOT NULL,
    SOLICITANTE VARCHAR(100) NOT NULL,
    CONCEPTO VARCHAR(255) NOT NULL,
    MONTO NUMERIC(15,2) NOT NULL,
    ESTATUS VARCHAR(30) DEFAULT 'Pendiente',
    FECHA_SOLICITUD TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 8. LICITACIONES Y SELECCIÓN
CREATE TABLE LICITACIONES_SELECCION (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_LICITACION VARCHAR(50) NOT NULL UNIQUE,
    SOLICITUD_ID BIGINT REFERENCES SOLICITUDES_COMPRA(ID) ON DELETE SET NULL,
    PROVEEDOR_GANADOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE SET NULL,
    MONTO_ADJUDICADO NUMERIC(15,2),
    ESTATUS_CONTRATO VARCHAR(50) DEFAULT 'Pendiente Firma Proveedor',
    CONTRATO_FIRMADO_PDF VARCHAR(255),
    FECHA_ADJUDICACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE LICITACION_OFERTAS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LICITACION_ID BIGINT REFERENCES LICITACIONES_SELECCION(ID) ON DELETE CASCADE,
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE CASCADE,
    PRECIO_OFERTA NUMERIC(15,2) NOT NULL,
    DIAS_ENTREGA INT,
    PUNTAJE_CALIDAD NUMERIC(5,2),
    GARANTIA VARCHAR(100),
    ES_GANADOR INT DEFAULT 0
);

-- 9. ÓRDENES DE COMPRA Y DETALLES
CREATE TABLE ORDENES_COMPRA (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR(50) NOT NULL UNIQUE,
    LICITACION_ID BIGINT REFERENCES LICITACIONES_SELECCION(ID) ON DELETE SET NULL,
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE SET NULL,
    PROVEEDOR VARCHAR(150),
    MONTO_TOTAL NUMERIC(15,2) NOT NULL DEFAULT 0,
    ESTATUS_ENTREGA VARCHAR(50) DEFAULT 'En Proceso Almacén',
    ESTATUS VARCHAR(50) DEFAULT 'Emitida',
    FECHA_EMISION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ORDENES_COMPRA_ITEMS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OC_ID BIGINT REFERENCES ORDENES_COMPRA(ID) ON DELETE CASCADE,
    DESCRIPCION VARCHAR(255),
    CANTIDAD NUMERIC(15,2),
    PRECIO_UNITARIO NUMERIC(15,2),
    SUBTOTAL NUMERIC(15,2)
);

-- 10. RECEPCIONES DE ALMACÉN
CREATE TABLE RECEPCIONES_ALMACEN (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR(50) UNIQUE,
    OC_ID BIGINT REFERENCES ORDENES_COMPRA(ID) ON DELETE SET NULL,
    OC_CODIGO VARCHAR(50),
    PROVEEDOR VARCHAR(150),
    FECHA_RECEPCION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ESTADO VARCHAR(50) DEFAULT 'Recibida',
    NOTAS TEXT
);

CREATE TABLE RECEPCIONES_ALMACEN_ITEMS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RECEPCION_ID BIGINT REFERENCES RECEPCIONES_ALMACEN(ID) ON DELETE CASCADE,
    DESCRIPCION VARCHAR(255),
    CANTIDAD_RECIBIDA NUMERIC(15,2),
    ESTADO_ITEM VARCHAR(50)
);

-- 11. CUENTAS POR PAGAR (CXP)
CREATE TABLE CXP (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FACTURA VARCHAR(50) UNIQUE,
    NUMERO_FACTURA VARCHAR(50),
    ORDEN_COMPRA_ID BIGINT REFERENCES ORDENES_COMPRA(ID) ON DELETE SET NULL,
    OC_CODIGO VARCHAR(50),
    RECEPCION_ID BIGINT REFERENCES RECEPCIONES_ALMACEN(ID) ON DELETE SET NULL,
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE SET NULL,
    PROVEEDOR VARCHAR(150),
    EMISION DATE DEFAULT CURRENT_DATE,
    VENCIMIENTO DATE,
    SUBTOTAL NUMERIC(15,2) DEFAULT 0,
    MONTO_IVA NUMERIC(15,2) DEFAULT 0,
    MONTO_ISLR_RETENIDO NUMERIC(15,2) DEFAULT 0,
    MONTO_NETO NUMERIC(15,2) DEFAULT 0,
    MONTO NUMERIC(15,2) DEFAULT 0,
    ESTATUS VARCHAR(50) DEFAULT 'Pendiente',
    MONEDA VARCHAR(10) DEFAULT 'USD',
    TASA_CAMBIO NUMERIC(15,4) DEFAULT 1.0,
    BANCO_PAGO VARCHAR(100),
    MOTIVO_DEVOLUCION TEXT,
    FECHA_EMISION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE FACTURAS_CXP (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_FACTURA VARCHAR(50) NOT NULL UNIQUE,
    ORDEN_COMPRA_ID BIGINT REFERENCES ORDENES_COMPRA(ID) ON DELETE SET NULL,
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE SET NULL,
    MONTO_FACTURA NUMERIC(15,2) NOT NULL,
    FECHA_EMISION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_VENCIMIENTO DATE,
    ESTATUS_PAGO VARCHAR(50) DEFAULT 'Aprobada para Pago'
);

-- 12. RETENCIONES Y PAGOS
CREATE TABLE RETENCIONES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CXP_ID BIGINT REFERENCES CXP(ID) ON DELETE CASCADE,
    TIPO_RETENCION VARCHAR(50),
    PORCENTAJE NUMERIC(5,2),
    MONTO NUMERIC(15,2),
    COMPROBANTE VARCHAR(50),
    FECHA TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE PAGOS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REFERENCIA VARCHAR(50) UNIQUE,
    REFERENCIA_PAGO VARCHAR(50),
    CXP_ID BIGINT REFERENCES CXP(ID) ON DELETE SET NULL,
    FACTURA_ID BIGINT REFERENCES CXP(ID) ON DELETE SET NULL,
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE SET NULL,
    PROVEEDOR VARCHAR(150),
    BANCO_ORIGEN VARCHAR(100) DEFAULT 'Banco Mercantil',
    CUENTA_ORIGEN VARCHAR(30),
    CUENTA_DESTINO VARCHAR(30),
    MONTO NUMERIC(15,2) NOT NULL,
    MONTO_LIQUIDADO NUMERIC(15,2),
    FECHA DATE DEFAULT CURRENT_DATE,
    ESTATUS VARCHAR(30) DEFAULT 'Procesado'
);

CREATE TABLE PAGOS_LIQUIDADOS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REFERENCIA_PAGO VARCHAR(50) NOT NULL UNIQUE,
    FACTURA_ID BIGINT REFERENCES FACTURAS_CXP(ID) ON DELETE SET NULL,
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE SET NULL,
    BANCO_ORIGEN VARCHAR(100) DEFAULT 'Banco Mercantil',
    CUENTA_DESTINO VARCHAR(30) NOT NULL,
    MONTO_LIQUIDADO NUMERIC(15,2) NOT NULL,
    FECHA_PAGO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ESTATUS VARCHAR(30) DEFAULT 'Procesado'
);

