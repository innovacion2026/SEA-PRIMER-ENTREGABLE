-- 1. MAESTRO DE PROVEEDORES
CREATE TABLE PROVEEDORES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RIF VARCHAR(20) NOT NULL UNIQUE,
    NOMBRE VARCHAR(150) NOT NULL,
    CATEGORIA VARCHAR(100),
    ZONA VARCHAR(100),
    CONTACTO VARCHAR(100),
    TELEFONO VARCHAR(30),
    EMAIL VARCHAR(100),
    BANCO VARCHAR(100),
    CUENTA_BANCARIA VARCHAR(30),
    EVALUACION NUMERIC(5,2),
    ESTATUS VARCHAR(30) DEFAULT 'Activo',
    FECHA_INGRESO DATE DEFAULT CURRENT_DATE,
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. SOLICITUDES DE PROVEEDORES
CREATE TABLE SOLICITUDES_PROVEEDOR (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR(50),
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE SET NULL,
    PROVEEDOR VARCHAR(150) NOT NULL,
    RIF VARCHAR(20) NOT NULL,
    CONTACTO VARCHAR(100),
    TELEFONO VARCHAR(30),
    EMAIL VARCHAR(100),
    FECHA DATE DEFAULT CURRENT_DATE,
    TIPO VARCHAR(50),
    ETAPA VARCHAR(50),
    CATEGORIA VARCHAR(100),
    ESTATUS VARCHAR(30) DEFAULT 'En revisión',
    TOKEN_INVITACION VARCHAR(100),
    BANCO_NOMBRE VARCHAR(100),
    CUENTA_20_DIGITOS VARCHAR(30),
    TITULAR_CUENTA VARCHAR(150),
    EXPEDIENTE_APROBADO INT DEFAULT 0,
    FECHA_INVITACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_REGISTRO TIMESTAMP
);

CREATE TABLE SOLICITUDES_INGRESO_PROVEEDOR (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RIF VARCHAR(20) NOT NULL,
    PROVEEDOR VARCHAR(150) NOT NULL,
    CATEGORIA VARCHAR(100),
    EMAIL VARCHAR(100) NOT NULL,
    TELEFONO VARCHAR(30),
    ESTATUS VARCHAR(30) DEFAULT 'Invitado',
    TOKEN_INVITACION VARCHAR(100),
    BANCO_NOMBRE VARCHAR(100),
    CUENTA_20_DIGITOS VARCHAR(30),
    TITULAR_CUENTA VARCHAR(150),
    EXPEDIENTE_APROBADO INT DEFAULT 0,
    FECHA_INVITACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_REGISTRO TIMESTAMP
);

-- 3. EVALUACIONES Y NOTIFICACIONES DE PROVEEDORES
CREATE TABLE EVALUACIONES_PROVEEDOR (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE CASCADE,
    PUNTAJE NUMERIC(5,2),
    COMENTARIO TEXT,
    FECHA_EVALUACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE NOTIFICACIONES_PROVEEDOR (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE CASCADE,
    TITULO VARCHAR(150),
    MENSAJE TEXT,
    LEIDO INT DEFAULT 0,
    FECHA TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. DOCUMENTACIÓN DE PROVEEDORES
CREATE TABLE DOCUMENTACION_PROVEEDOR (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE CASCADE,
    NOMBRE_DOCUMENTO VARCHAR(150) NOT NULL,
    CATEGORIA VARCHAR(100),
    NOMBRE_ARCHIVO_PDF VARCHAR(255) NOT NULL,
    PESO_ARCHIVO VARCHAR(30),
    FECHA_CARGA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_VENCIMIENTO DATE,
    ESTATUS_VALIDACION VARCHAR(30) DEFAULT 'PENDIENTE',
    ORIGEN_CARGA VARCHAR(50) DEFAULT 'Portal Proveedores'
);

CREATE TABLE DOCUMENTOS_PROVEEDOR (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROVEEDOR_ID BIGINT REFERENCES PROVEEDORES(ID) ON DELETE CASCADE,
    NOMBRE_DOCUMENTO VARCHAR(150) NOT NULL,
    CATEGORIA VARCHAR(100),
